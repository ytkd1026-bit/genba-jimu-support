// ============================================================
// SheetLayout — このファイルの責務
// ------------------------------------------------------------
// ・帳票「画面」のレイアウト定数（A4横表示専用）
// ・画面のページ分割計算は必ずここを参照する
// ・PDFとの改ページ位置の一致は保証しない（PDFはreact-pdfが自前で改ページする）
// ・寸法の数値をこのファイル以外へ散らさない
// ・変更時はこのファイルだけを触れば済む状態を保つ
// ・使う側: estimateSheetPagination.ts
// ============================================================
//
// 帳票レイアウトの寸法定数。
//
// 画面の改ページに関わる数値はすべてここに集約する。コード内へ散らさない。
// 変更するときはこのファイルだけを触れば済む状態を保つこと。
//
// 単位の考え方:
//   明細1行を 1単位 とし、ヘッダーや小計が占める領域を単位数で見積もる。
//   高さを実測する仕組みは持たない（複雑になるため）。
//   実測値にもとづく概算で、実用上自然に見えれば十分とする。
//
// 数値の根拠（2026-07-20 時点の実測）:
//   A4横の用紙は幅1123pxのとき高さ約800px、内側余白を除くと約750pxが使える。
//   明細1行は施工箇所が location1 / location2 の2段になるため約48px。
//   → 750 / 48 ≒ 15。見出しと小計の分を引いて 14単位とした。
//
// PDF との関係:
//   PDF は react-pdf が自前で改ページするため、この値を参照しない。
//   画面と PDF でページ数が異なるのは想定内。ページ判定は PDF を正とする。
//   一致させるのは 工種の順番／まとまり／工種小計／諸経費が最後／
//   総合計が最後／（続き）表示 の6点のみ。

export type SheetLayout = {
  /** 1ページに入る単位数（明細1行 = 1単位） */
  pageCapacity: number;
  /** 帳票ヘッダー（提出先・自社情報・税込見積金額）が占める単位数。1ページ目のみ */
  headerUnits: number;
  /** 工種見出し（【内装工事】）が占める単位数 */
  headingUnits: number;
  /** 工種小計が占める単位数 */
  subtotalUnits: number;
  /** 全体合計（小計・消費税・税込合計）が占める単位数 */
  grandTotalUnits: number;
};

/** A4横・見積明細書の既定レイアウト */
export const A4_LANDSCAPE_ESTIMATE: SheetLayout = {
  pageCapacity: 14,
  headerUnits: 6,
  headingUnits: 1,
  subtotalUnits: 1,
  grandTotalUnits: 2,
};

/**
 * 既定のレイアウト。
 * 将来、帳票種別ごとや用紙向きごとに切り替える場合は、
 * ここへ別の SheetLayout を追加して呼び出し元で選択する。
 */
export const DEFAULT_SHEET_LAYOUT: SheetLayout = A4_LANDSCAPE_ESTIMATE;
